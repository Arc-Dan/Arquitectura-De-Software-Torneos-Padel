    private void btnGuardarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnGuardarMouseClicked
    
        Jugador jugador = new  Jugador(
                tfNombre.getText(),
                tfTelefono.getText(),
                tfCorreo.getText(),
                Integer.parseInt( tfNivel.getText() ),
                tfCiudad.getText(),
                Integer.parseInt( tfEdad.getText() )
        );
        
        if(this.jugador==null){ 
            if( jugadorController.crear(jugador) ){
                this.setVisible(false);
            }else{ 
                JOptionPane.showMessageDialog(this, "Error al algregar el jugador"); 
            }
        }else{ 
           if(jugadorController.editar(jugador)){
                this.setVisible(false);
           }else{
               JOptionPane.showMessageDialog(this, "Error al editar el jugador"); 
           } 
        }
        
        
        
        
        
        
    }//GEN-LAST:event_btnGuardarMouseClicked

    private void btnEliminarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnEliminarMouseClicked
     
      if( jugadorController.eliminar(jugador) ){
       JOptionPane.showMessageDialog(null, "Judagador eliminador correctamente");
       this.setVisible(false);
      }else{
       JOptionPane.showMessageDialog(this, "Se presento un error al eliminar! x__X");
      }
        
        
        
    }//GEN-LAST:event_btnEliminarMouseClicked

