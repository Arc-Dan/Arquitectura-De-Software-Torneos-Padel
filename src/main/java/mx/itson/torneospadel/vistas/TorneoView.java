    public void llenarTabla(){  
       lista = torneoController.listar();  
       DefaultTableModel model = new DefaultTableModel(); 
       model.addColumn("Nombre");   model.addColumn("Club");
       model.addColumn("Fecha");   model.addColumn("Precio"); 
        model.addColumn("Nivel");  
      for(Torneo t :lista ){ 
       model.addRow( new Object[]{
           t.getNombre(),
           t.getClub().getNombre(),
           t.getFecha(),
           t.getPrecio(),
           t.getNivel()
       }); 
      }  
      tblTorneos.setModel(model);
    }
    

