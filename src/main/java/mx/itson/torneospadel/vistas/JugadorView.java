    public void llenarTabla(){  
       lista = jugadorController.listar(); 
      //modelo: crear columnas y filas
       DefaultTableModel model = new DefaultTableModel(); 
       model.addColumn("Nombre");   model.addColumn("Telefono");
       model.addColumn("Correo");   model.addColumn("Nivel");
       model.addColumn("Ciudad");   model.addColumn("Edad");
      //llenar la tabla
      for(Jugador j :lista ){ 
       model.addRow( new Object[]{
         j.getNombre(), j.getTelefono(),  j.getCorreo(),
           j.getNivel(), j.getCiudad(),  j.getEdad()
       }); 
      } 
      //agregar modelo a la tabla
      tblJugadores.setModel(model);
    }
    

