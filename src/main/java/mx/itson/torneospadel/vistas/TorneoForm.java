    private void btnGuardarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnGuardarMouseClicked
        Club clubSeleccionado = null;
        for(Club c : listaClubs){
            if(c.getNombre().equals(cbClub.getSelectedItem()+"")){
                clubSeleccionado = c;
            }
        }
        
        Torneo torneo = new  Torneo(
                tfNombre.getText(),
                clubSeleccionado,
                tfFecha.getText(),
                Double.parseDouble( tfPrecio.getText() ),
                Integer.parseInt( tfNivel.getText() )
        );
        
        if(this.torneo==null){ 
            if( torneoController.crear(torneo) ){
                this.setVisible(false);
            }else{ 
                JOptionPane.showMessageDialog(this, "Error al algregar el jugador"); 
            }
        }else{ 
           if(torneoController.editar(torneo)){
                this.setVisible(false);
           }else{
               JOptionPane.showMessageDialog(this, "Error al editar el jugador"); 
           } 
        }    }//GEN-LAST:event_btnGuardarMouseClicked

    private void btnEliminarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnEliminarMouseClicked
      if( torneoController.eliminar(torneo) ){
       JOptionPane.showMessageDialog(null, "Torneo eliminador correctamente");
       this.setVisible(false);
      }else{
       JOptionPane.showMessageDialog(this, "Se presento un error al eliminar");
      }    }//GEN-LAST:event_btnEliminarMouseClicked

